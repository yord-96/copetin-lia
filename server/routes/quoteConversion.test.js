import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import express from 'express';

test('quote conversion is authoritative, atomic, versioned and safe to retry concurrently', async () => {
  const directory = await fs.mkdtemp(path.join(os.tmpdir(), 'copetin-conversion-'));
  process.env.APP_STATE_FILE = path.join(directory, 'state.json');
  process.env.APP_INTERNAL_KEY = 'conversion-test-key';
  const { default: router } = await import('./contractTransactions.js');
  const { replaceStateSnapshot, getStateSnapshot } = await import('../storage/fileStateStore.js');
  const { getWebBridge } = await import('../../src/services/webBridge.js');
  const seed = await getWebBridge().__storage.exportState();
  await replaceStateSnapshot({ ...seed, items: [{ id: 'chair', name: 'SILLA', controlsStock: true, totalStock: 20, availableStock: 20, rentalPriceBs: 10 }], quotes: [], contracts: [], rentals: [], cashMovements: [], inventoryMovements: [], deliveries: [], clients: [], settings: { ...seed.settings, numbering: { ...seed.settings.numbering, quotePrefix: 'COT', quoteNext: 1, contractNext: 1, orderNext: 1 } } }, null);
  const app = express(); app.use(express.json()); app.use(router);
  app.use((error, req, res, next) => { void next; res.status(error.statusCode || 400).json({ error: error.message }); });
  const server = app.listen(0, '127.0.0.1'); await new Promise(resolve => server.once('listening', resolve));
  const url = `http://127.0.0.1:${server.address().port}/__copetin_db`;
  const post = (suffix, body) => fetch(url + suffix, { method: 'POST', headers: { 'Content-Type': 'application/json', 'X-App-Internal-Key': 'conversion-test-key' }, body: JSON.stringify(body) });
  const input = { customerName: 'QA CLIENTE', customerPhone: '70000000', eventDate: '2026-11-22', eventTime: '12:00', deliveryDate: '2026-11-22', pickupDate: '2026-11-23', address: 'QA', logisticsMode: 'recojo', guaranteeBs: 200, guaranteeStatus: 'no_validado', items: [{ itemId: 'chair', quantity: 2, unitPriceBs: 10 }] };
  try {
    let response = await post('/quotes/create', { quote: input, operationId: 'conversion-quote-001' });
    assert.equal(response.status, 200, await response.clone().text());
    const quote = (await response.json()).quote;
    const body = { quoteUpdatedAt: quote.updatedAt, trace: { userId: 'qa', userName: 'QA', createdByName: 'QA' } };
    response = await post(`/quotes/${quote.id}/convert`, { ...body, quoteUpdatedAt: 'old' });
    assert.equal(response.status, 409);
    assert.equal((await getStateSnapshot()).state.contracts.length, 0);
    const results = await Promise.all([post(`/quotes/${quote.id}/convert`, body), post(`/quotes/${quote.id}/convert`, body)]);
    for (const result of results) assert.equal(result.status, 200, await result.clone().text());
    const [first, retry] = await Promise.all(results.map(result => result.json()));
    assert.equal(first.contract.id, retry.contract.id);
    assert.equal(first.rental.id, retry.rental.id);
    assert.equal(first.contract.totals.totalBs, 20);
    assert.equal(first.contract.totals.guaranteeBs, 200);
    assert.equal(first.contract.rentalId, first.rental.id);
    let state = (await getStateSnapshot()).state;
    assert.equal(state.contracts.length, 1); assert.equal(state.rentals.length, 1);
    assert.equal(state.quotes[0].status, 'aprobada');
    assert.equal(state.quotes[0].convertedContractId, first.contract.id);
    const originalStock = state.items[0].availableStock;
    const originalMovements = state.inventoryMovements.length;
    response = await post(`/quotes/${quote.id}/convert`, body);
    assert.equal(response.status, 200);
    state = (await getStateSnapshot()).state;
    assert.equal(state.items[0].availableStock, originalStock);
    assert.equal(state.inventoryMovements.length, originalMovements);
    // Failure after contract creation must roll back the whole conversion.
    response = await post('/quotes/create', { quote: { ...input, items: [{ itemId: 'chair', quantity: 999, unitPriceBs: 10 }] }, operationId: 'conversion-quote-002' });
    const unavailable = (await response.json()).quote;
    response = await post(`/quotes/${unavailable.id}/convert`, { quoteUpdatedAt: unavailable.updatedAt, trace: body.trace });
    assert.notEqual(response.status, 200);
    state = (await getStateSnapshot()).state;
    assert.equal(state.contracts.length, 1); assert.equal(state.rentals.length, 1);
    assert.equal(state.quotes.find(row => row.id === unavailable.id).status, 'borrador');
    const cashBefore = state.cashMovements.length;
    response = await post('/quotes/create', { quote: { ...input, paidAtApprovalBs: 10, guaranteeStatus: 'validado' }, operationId: 'conversion-quote-003' });
    const paidQuote = (await response.json()).quote;
    const paidBody = { quoteUpdatedAt: paidQuote.updatedAt, trace: body.trace };
    response = await post(`/quotes/${paidQuote.id}/convert`, paidBody);
    assert.equal(response.status, 200, await response.clone().text());
    state = (await getStateSnapshot()).state;
    const cashCount = state.cashMovements.length;
    assert.ok(cashCount > cashBefore, 'paid quote must produce real initial cash entries');
    const cashTotal = state.cashMovements.reduce((sum, row) => sum + Number(row.amountBs), 0);
    assert.equal(cashTotal, 210, 'payment and guarantee remain separate and preserved');
    response = await post(`/quotes/${paidQuote.id}/convert`, paidBody);
    assert.equal(response.status, 200);
    const repeated = await response.json();
    assert.ok(repeated.changes.cashMovements.length > 0, 'a recovered response includes its existing receipts');
    assert.equal((await getStateSnapshot()).state.cashMovements.length, cashCount, 'retry must never collect twice');
    response = await post('/contracts/create-and-approve', { contract: input, trace: body.trace });
    assert.equal(response.status, 200, 'ordinary contract approvals must keep working: ' + await response.clone().text());
  } finally {
    await new Promise(resolve => server.close(resolve));
    if (directory.startsWith(path.join(os.tmpdir(), 'copetin-conversion-'))) await fs.rm(directory, { recursive: true, force: true });
  }
});
